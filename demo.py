"""Run every scenario of the SAU Smart Campus Navigator and write
outputs/results.md plus figures and the interactive map.

    python demo.py
"""
from __future__ import annotations

import math
from pathlib import Path

from navigator import viz
from navigator.agent import NavigatorAgent, label
from navigator.graph import campus
from navigator.multistop import Stop, TourPlanner, follow_with_replanning
from navigator.problem import Profile
from navigator.webmap import write_map

OUT = Path(__file__).resolve().parent / "outputs"
OUT.mkdir(exist_ok=True)
md: list[str] = []


def say(text=""):
    print(text)
    md.append(text)


def table(rows, cols=None):
    cols = cols or list(rows[0])
    say("| " + " | ".join(cols) + " |")
    say("|" + "|".join("---" for _ in cols) + "|")
    for r in rows:
        say("| " + " | ".join(str(r[c]) for c in cols) + " |")
    say()


def code(text):
    say("```")
    say(text)
    say("```")
    say()


def main():
    g = campus()
    agent = NavigatorAgent(g)
    say("# SAU Smart Campus Navigator: demo results\n")
    say("Generated by `python demo.py`. All numbers come from the surveyed SAU graph.\n")

    # 0 ---------------------------------------------------------------- graph
    say("## 0. Campus graph\n")
    code(g.summary())
    if g.warnings:
        say("Builder warnings: " + "; ".join(g.warnings) + "\n")
    steep = sum(1 for e in g.edges.values() if e.grade > 0.0833)
    say(f"{steep} lane segments are steeper than the 1:12 wheelchair limit (from survey altitudes).\n")
    viz.campus_figure(g, OUT / "00_campus_graph.png", "SAU campus graph built from GPS survey")
    say("![graph](00_campus_graph.png)\n")

    # 1 ---------------------------------------------------- algorithm comparison
    say("## 1. Uninformed vs informed search (on foot, Boys' Hostel to AB4, minimise time)\n")
    rows = agent.compare("BOYS_HOSTEL", "AB4")
    table(rows, ["algorithm", "found", "cost", "steps", "expanded", "generated", "max_frontier", "runtime_ms"])
    say("Cost is expected seconds. BFS minimises *steps*, not time; DFS returns the first route it stumbles on. "
        "UCS and A* both return the optimum, but A* (straight-line heuristic) expands fewer nodes, and the "
        "landmark (ALT) heuristic is tighter still. Weighted A* (w=2) expands the fewest nodes; it is only "
        "guaranteed within 2x of optimal, though here it happens to find the optimum.\n")
    res = [agent.route("BOYS_HOSTEL", "AB4", algorithm=a).result for a in ("bfs", "dfs", "ucs", "greedy", "astar")]
    alt = agent.route("BOYS_HOSTEL", "AB4", heuristic="alt").result
    alt.algorithm = "A* + ALT"
    res.append(alt)
    viz.explored_figure(g, res, OUT / "01_explored.png", "Nodes expanded (red) and route found (black)")
    viz.bar_figure(rows, OUT / "01_expanded_bar.png", "Nodes expanded, Boys' Hostel to AB4")
    say("![explored](01_explored.png)\n\n![bar](01_expanded_bar.png)\n")

    say("**Average over all place pairs (walking, time):**\n")
    pairs = [(a, b) for a in g.places for b in g.places if a < b]
    agg = {}
    for a, b in pairs:
        for name, kw in [("UCS", dict(algorithm="ucs")), ("A*", dict(algorithm="astar")),
                         ("A* + ALT", dict(algorithm="astar", heuristic="alt")),
                         ("Greedy", dict(algorithm="greedy")), ("BFS", dict(algorithm="bfs"))]:
            r = agent.route(a, b, **kw).result
            s = agg.setdefault(name, {"expanded": 0, "cost": 0.0})
            s["expanded"] += r.expanded
            s["cost"] += r.cost
    opt = agg["UCS"]["cost"]
    table([{"algorithm": k, "avg expanded": round(v["expanded"] / len(pairs), 1),
            "total cost vs optimal": f"{v['cost'] / opt:.3f}x"} for k, v in agg.items()])

    # 2 ------------------------------------------------------------- vehicles
    say("## 2. Vehicle modes: who may use which path\n")
    say("| layer | walk | 2-wheeler | 4-wheeler |\n|---|---|---|---|\n| lane (SAU_Project_1) | yes | yes | no |\n"
        "| road (Vehicle-only route) | yes | yes | yes |\n| entrance link | yes | no | no |\n\n"
        "Vehicles must park at one of the 10 parking spots; A* chooses the spot as part of the search.\n")
    trips = []
    for start, goal, prof, tag in [
        ("GATE1", "LIBRARY", Profile("walk"), "walk"),
        ("GATE1", "LIBRARY", Profile("bike"), "2-wheeler"),
        ("GATE1", "LIBRARY", Profile("car"), "4-wheeler"),
        ("GATE3", "FACULTY_RES", Profile("car", role="student"), "4-wheeler, student"),
        ("GATE3", "FACULTY_RES", Profile("car", role="faculty"), "4-wheeler, faculty"),
        ("BOYS_HOSTEL", "AB4", Profile("bike"), "2-wheeler from hostel"),
        ("BOYS_HOSTEL", "AB4", Profile("car"), "4-wheeler from hostel"),
    ]:
        r = agent.route(start, goal, prof)
        trips.append((tag, r))
        say(f"**{tag}**")
        code(r.describe())
    say("Note the last case: fetching the car (3 min) and parking it again (3 min) costs more than walking, "
        "so the agent leaves it parked. Faculty may use Faculty Parking; students may not "
        "(rules in `data/overrides.json`).\n")
    viz.routes_figure(g, [trips[2]], OUT / "02_car_gate1_library.png",
                      "4-wheeler: Gate 1 to Library (drive pink, park *, walk green)")
    viz.routes_figure(g, [trips[5]], OUT / "02_bike_hostel_ab4.png",
                      "2-wheeler: Boys' Hostel to AB4 (walk, collect bike, ride, park, walk)")
    say("![car](02_car_gate1_library.png)\n\n![bike](02_bike_hostel_ab4.png)\n")

    # 3 ------------------------------------------------------------- closures
    say("## 3. Closures\n")
    base = agent.route("BOYS_HOSTEL", "AB4")
    mid_eids = [v for k, v in base.result.actions if k == "move"]
    e = g.edges[mid_eids[len(mid_eids) // 2]]
    a_, b_ = g.nodes[e.u], g.nodes[e.v]
    agent.report_closure((a_.lat + b_.lat) / 2, (a_.lon + b_.lon) / 2, radius_m=10)
    detour = agent.route("BOYS_HOSTEL", "AB4")
    say(f"Closing a 10 m radius around the midpoint of the normal route blocks {len(agent.closures.blocked)} edges.")
    code("Before:\n" + base.describe() + "\n\nAfter closure:\n" + detour.describe())
    viz.routes_figure(g, [("usual route", base), ("with closure", detour)], OUT / "03_closure.png",
                      "Construction closure (red X) forces a detour", closures=agent.closures)
    say("![closure](03_closure.png)\n")
    agent.clear_closures()

    say("**Car entrance of Library UG Parking closed** (cars only; pedestrians and 2-wheelers unaffected):\n")
    car = agent.route("GATE1", "LIBRARY", Profile("car"))
    lp = g.parking["Library UG Parking"]
    agent.closures.close([eid for eid in g.adj[lp] if "car" in g.edges[eid].modes], modes=("car",))
    car2 = agent.route("GATE1", "LIBRARY", Profile("car"))
    bike2 = agent.route("GATE1", "LIBRARY", Profile("bike"))
    code(car.describe() + "\n\nAfter closure, 4-wheeler:\n" + car2.describe()
         + "\n\nAfter closure, 2-wheeler (still allowed in):\n" + bike2.describe())
    say("The agent re-chooses the parking spot as part of the same A* search.\n")
    agent.clear_closures()

    say("**Discovering a closure mid-trip (online replanning):**\n")
    hidden = [mid_eids[len(mid_eids) // 2]]
    run = follow_with_replanning(agent, "BOYS_HOSTEL", "AB4", hidden_closures=hidden)
    for ev in run["log"]:
        if ev[0] == "plan":
            say(f"- plan: {len(ev[1])} nodes, expected {ev[2] / 60:.1f} min")
        elif ev[0] == "replan":
            say(f"- at node {ev[1]} the agent sees edge(s) {ev[2]} closed and replans from there: "
                f"{ev[4] / 60:.1f} min remaining")
    say(f"- reached goal: {run['reached']}\n")

    # 4 --------------------------------------------------------- accessibility
    say("## 4. Accessibility\n")
    n = agent.route("AMPHITHEATRE", "KITCHEN")
    w = agent.route("AMPHITHEATRE", "KITCHEN", Profile(wheelchair=True))
    code("Standard:\n" + n.describe() + "\n\nWheelchair:\n" + w.describe())
    say("The wheelchair profile forbids edges with stairs (`overrides.json`) or a grade above 1:12, "
        "slows down on grades above 5 %, and uses 0.9 m/s.\n")
    steep_trips = 0
    for a, b in pairs:
        r = agent.route(a, b)
        if any(k == "move" and g.edges[v].grade > 0.0833 for k, v in r.result.actions):
            steep_trips += 1
    say(f"{steep_trips} of {len(pairs)} shortest walking routes include a segment steeper than 1:12; "
        "the wheelchair profile reroutes all of them.\n")
    viz.routes_figure(g, [("standard", n), ("wheelchair", w)], OUT / "04_wheelchair.png",
                      "Wheelchair route avoids stairs and steep segments")
    say("![wheelchair](04_wheelchair.png)\n")
    r1 = agent.route("GATE3", "UG_PARKING2")
    r2 = agent.route("GATE3", "UG_PARKING2", Profile(avoid_roads=1.6))
    say(f"Preference `avoid_roads=1.6` (pedestrian dislikes vehicle roads): Gate 3 to UG Parking 2 goes "
        f"{r1.distance_m():.0f} m to {r2.distance_m():.0f} m, staying on the lane.\n")

    # 5 ------------------------------------------------------------ uncertainty
    say("## 5. Travel-time uncertainty\n")
    say("Edge times are log-normal; hotspots (mess at lunch, academic blocks at class change, main gate at "
        "rush hour) raise both mean and variance. Monte Carlo: 5000 samples.\n")
    rows = []
    for s_, t_, dep, met, dl in [("AB1", "CONVENTION", "10:00", "time", None),
                                 ("AB1", "CONVENTION", "13:00", "time", None),
                                 ("LIBRARY", "AB4", "09:55", "time", 487),
                                 ("LIBRARY", "AB4", "09:55", "safe", 487)]:
        r = agent.route(s_, t_, depart=dep, metric=met)
        st = agent.reliability(r, dl)
        rows.append({"trip": f"{s_} to {t_}", "depart": dep, "objective": met,
                     "distance m": round(r.distance_m()), "mean s": round(st["mean_s"]),
                     "p95 s": round(st["p95_s"]), "p95-p50 spread": round(st["p95_s"] - st["p50_s"]),
                     "P(on time, 487 s)": f"{st['p_on_time']:.2f}" if dl else "-"})
        if dep == "09:55":
            rows[-1]["_route"] = r
    table(rows, [k for k in rows[0] if not k.startswith("_")])
    say("At 13:00 the fastest AB1 to Convention route bends away from the busy mess area. "
        "At 09:55 (class change) the fastest Library to AB4 route cuts through the academic-block crowd: "
        "a lower mean but a wide spread. The risk-averse objective (mean + 1.5 sd per edge) picks a route "
        "that is slower on average but far more predictable, so with an 8.1-minute deadline it is on time "
        "much more often. Fastest-on-average is not the same as most likely to be on time.\n")
    viz.routes_figure(g, [("fastest (mean)", rows[2]["_route"]), ("risk-averse", rows[3]["_route"])],
                      OUT / "05_risk.png", "Library to AB4 at 09:55: fastest vs risk-averse")
    say("![risk](05_risk.png)\n")

    # 6 -------------------------------------------------------------- multistop
    say("## 6. Multi-stop routing under deadlines (CSP + local search)\n")
    stops = [Stop("HEALTH", deadline="09:15", service_min=5),
             Stop("ADMIN", opens="09:10", deadline="09:20", service_min=10),
             Stop("LIBRARY", service_min=8),
             Stop("MESS3", opens="09:30", service_min=15),
             Stop("AB3", deadline="10:00", service_min=5)]
    tp = TourPlanner(agent, "BOYS_HOSTEL", stops, depart="09:00", end="AB4", end_deadline="10:10",
                     precedence=[("LIBRARY", "AB3")])
    say("Start Boys' Hostel 09:00. Health Centre before 09:15; Admin opens 09:10, deadline 09:20, 10 min there; "
        "Library (8 min) **before** AB3; Mess 3 opens 09:30, 15 min; AB3 by 10:00; finish at AB4 by 10:10.\n")
    say(f"Travel-time matrix: {tp.matrix_stats['pairs']} A* searches, "
        f"{tp.matrix_stats['astar_expanded']} nodes expanded, {tp.matrix_stats['ms']} ms.\n")
    csp = tp.solve_csp()
    plain = tp.solve_csp(forward_checking=False, branch_and_bound=False, value_order=None)
    plain.method = "Plain backtracking"
    sa = tp.solve_anneal()
    hc = tp.solve_hill_climb()
    bf = tp.solve_brute()
    for r in (csp, plain, bf, sa, hc):
        code(r.describe())
    say(f"Monte Carlo P(every deadline met) for the CSP plan: **{tp.on_time_probability(csp):.2f}**\n")
    viz.anneal_figure(sa.trace, tp.cost(csp.order), OUT / "06_annealing.png")
    say("![sa](06_annealing.png)\n")

    say("**Scaling to 9 stops** (9! = 362,880 orders):\n")
    big = [Stop(p, service_min=4) for p in ("AB1", "AB2", "AB5", "AB6", "AB7", "AB8", "LIBRARY", "HEALTH", "GUEST_HOUSE")]
    big[7].deadline = "09:20"
    big[0].deadline = "09:45"
    tp2 = TourPlanner(agent, "GATE1", big, depart="09:00")
    c2, s2, h2 = tp2.solve_csp(), tp2.solve_anneal(iters=6000), tp2.solve_hill_climb()
    table([{"method": r.method, "feasible": r.feasible, "finish": f"{r.finish_m - 540:.1f} min",
            "work": r.stats.get("nodes", r.stats.get("evaluations")), "ms": r.stats["ms"]} for r in (c2, s2, h2)])

    say("**Infeasible request:**\n")
    bad = TourPlanner(agent, "BOYS_HOSTEL", [Stop("AB4", deadline="09:04"), Stop("LIBRARY")], depart="09:00")
    code(bad.solve_csp().describe() + "\n\n" + bad.solve_anneal().describe())
    say("CSP proves no order works and says why; local search still returns the least-late order.\n")

    # maps & web apps -----------------------------------------------------
    write_map(g, OUT / "campus_map.html")
    say("Interactive satellite map: `outputs/campus_map.html` (needs internet for ESRI satellite tiles).")
    say("Interactive vector application: `web/index.html` (or `outputs/navigator_app.html`).")
    (OUT / "results.md").write_text("\n".join(md), encoding="utf-8")
    print(f"\nWrote {OUT / 'results.md'}")


if __name__ == "__main__":
    main()
